-- PUNTO 4: VERIFICAR LA GESTION DE UNDO
SELECT NAME, VALUE
FROM V$PARAMETER
WHERE NAME IN ('undo_management', 'undo_tablespace');


-- PUNTO 4: CONSULTAR LOS SEGMENTOS DE ROLLBACK
-- Oracle administra los segmentos automaticamente (UNDO = AUTO)

SELECT SEGMENT_NAME,
       TABLESPACE_NAME,
       STATUS
FROM DBA_ROLLBACK_SEGS
ORDER BY TABLESPACE_NAME, SEGMENT_NAME;
